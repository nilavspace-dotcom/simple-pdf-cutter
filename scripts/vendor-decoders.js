#!/usr/bin/env node
/*
 * Regenerates the image decoders in vendor/pdfjs/ and vendor/jpeg-js/.
 *
 * The decoders ship as ES modules that load their WebAssembly with fetch(),
 * and neither works in a page opened straight from disk. This script turns
 * them into classic scripts (which also load in Node.js with require()) and
 * embeds the WebAssembly code as base64.
 *
 * Usage:
 *   git clone --depth 1 --branch <tag> https://github.com/mozilla/pdf.js
 *   npm pack jpeg-js@<version> && tar -xzf jpeg-js-<version>.tgz
 *   node scripts/vendor-decoders.js <pdf.js folder> <pdf.js tag> <jpeg-js package folder>
 */
'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const [pdfjsDir, pdfjsTag, jpegJsDir] = process.argv.slice(2);
if (!pdfjsDir || !pdfjsTag || !jpegJsDir) {
  console.error(
    'Usage: node scripts/vendor-decoders.js <pdf.js folder> <pdf.js tag> <jpeg-js folder>',
  );
  process.exit(2);
}

const root = path.join(__dirname, '..');
const written = [];

function write(relativePath, contents) {
  const file = path.join(root, relativePath);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents);
  written.push(relativePath);
}

function umd(globalName, header, body) {
  return `${header}
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.${globalName} = factory();
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
${body}
});
`;
}

/** Converts an Emscripten ES module (with optional .wasm) to a classic script. */
function convertEmscripten(source, wasm, globalName) {
  const sourceFile = path.join(pdfjsDir, source);
  let code = fs.readFileSync(sourceFile, 'utf8');
  const match = code.match(/export default (\w+);\s*$/);
  if (!match) throw new Error(`${source}: expected "export default <name>;" at the end`);
  // import.meta.url is only used to find the .wasm file, which is embedded instead.
  code = code.slice(0, match.index).replace(/import\.meta\.url/g, '""');
  if (/\bimport\b\s*[({."']|\bexport\b/.test(code.replace(/"[^"\n]*"|'[^'\n]*'/g, ''))) {
    throw new Error(`${source}: unexpected import/export left after conversion`);
  }
  const wasmBase64 = wasm ? fs.readFileSync(path.join(pdfjsDir, wasm)).toString('base64') : null;
  const header = `/* Generated by scripts/vendor-decoders.js from pdf.js ${pdfjsTag}: ${source}${
    wasm ? ` and ${wasm} (embedded as base64)` : ''
  }.\n * Do not edit. See LICENSE files in this folder. */`;
  return umd(
    globalName,
    header,
    `'use strict';\n${code}\nreturn { factory: ${match[1]}, wasm: ${JSON.stringify(wasmBase64)} };`,
  );
}

write(
  'vendor/pdfjs/jbig2.js',
  convertEmscripten('external/jbig2/jbig2.js', 'external/jbig2/jbig2.wasm', 'PdfjsJbig2'),
);
write(
  'vendor/pdfjs/jbig2-fallback.js',
  convertEmscripten('external/jbig2/jbig2_nowasm_fallback.js', null, 'PdfjsJbig2Fallback'),
);
write(
  'vendor/pdfjs/openjpeg.js',
  convertEmscripten(
    'external/openjpeg/openjpeg.js',
    'external/openjpeg/openjpeg.wasm',
    'PdfjsOpenJpeg',
  ),
);
write(
  'vendor/pdfjs/openjpeg-fallback.js',
  convertEmscripten('external/openjpeg/openjpeg_nowasm_fallback.js', null, 'PdfjsOpenJpegFallback'),
);
for (const [from, to] of [
  ['LICENSE', 'LICENSE'],
  ['external/jbig2/LICENSE_JBIG2', 'LICENSE_JBIG2'],
  ['external/jbig2/LICENSE_PDFJS_JBIG2', 'LICENSE_PDFJS_JBIG2'],
  ['external/openjpeg/LICENSE_OPENJPEG', 'LICENSE_OPENJPEG'],
  ['external/openjpeg/LICENSE_PDFJS_OPENJPEG', 'LICENSE_PDFJS_OPENJPEG'],
]) {
  write(`vendor/pdfjs/${to}`, fs.readFileSync(path.join(pdfjsDir, from)));
}

const jpegPackage = JSON.parse(fs.readFileSync(path.join(jpegJsDir, 'package.json'), 'utf8'));
const decoder = fs.readFileSync(path.join(jpegJsDir, 'lib/decoder.js'), 'utf8');
write(
  'vendor/jpeg-js/decoder.js',
  umd(
    'JpegJs',
    `/* Generated by scripts/vendor-decoders.js from jpeg-js ${jpegPackage.version}: lib/decoder.js.\n * Do not edit. See LICENSE in this folder. */`,
    // decoder.js assigns `module.exports = decode` when `module` exists.
    `var module = { exports: {} };\n${decoder}\nreturn { decode: module.exports };`,
  ),
);
write('vendor/jpeg-js/LICENSE', fs.readFileSync(path.join(jpegJsDir, 'LICENSE')));

for (const file of written.filter((name) => name.endsWith('.js'))) {
  const hash = crypto
    .createHash('sha256')
    .update(fs.readFileSync(path.join(root, file)))
    .digest('hex');
  console.log(`${hash}  ${file}`);
}
